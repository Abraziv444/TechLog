-- Два вида приоритета: красный и жёлтый треугольник.
--   jobs.prio_hard = true  — красный: карточка закреплена первой,
--                            порядок стрелками не меняется;
--   jobs.prio_hard = false — жёлтый: пометка важности, порядок свободный.
-- Существующие приоритеты становятся красными — так вело себя приложение
-- до этой версии.
-- Идемпотентно.
-- ============================================================
alter table public.jobs
  add column if not exists prio_hard boolean not null default true;
